//! Every name the parser knows: constants and functions with their ASCII and Unicode spellings.
//!
//! The constants and the functions of the `tet` / `tet-line` expression grammar keep their names
//! and meanings here.

use std::collections::HashMap;
use std::sync::OnceLock;

pub struct Const {
    pub name: &'static str,
    pub aliases: &'static str,
    pub unicode: &'static str,
    /// Defining expression; empty for a primitive symbol.
    pub def: &'static str,
    pub meaning: &'static str,
}

const fn c(
    name: &'static str,
    aliases: &'static str,
    unicode: &'static str,
    def: &'static str,
    meaning: &'static str,
) -> Const {
    Const {
        name,
        aliases,
        unicode,
        def,
        meaning,
    }
}

